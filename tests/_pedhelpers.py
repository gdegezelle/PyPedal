"""
Shared fixtures for the remediation test suite.

Loading a pedigree has two side effects that make naive tests hostile to the
working tree: ``NewPedigree.__init__`` installs a PyPedal-owned logfile
handler, and the analysis routines write ``<filetag>_*.dat`` files derived
from the pedfile path.

``filetag`` is overwritten unconditionally from ``kw['pedfile']``
(``pyp_newclasses.py:86``), so passing a ``filetag`` option does not redirect
that output. The only reliable way to keep a test run from writing into
the working tree is to copy the pedigree into a temporary directory
and load it from there, which is what ``load_corpus`` does. That also
guarantees the bytes fed to the loader are identical to the committed fixture.
"""
import contextlib
import logging
import os
import shutil
import tempfile

from PyPedal.pyp_newclasses import (
    PYPEDAL_LOGGER_NAME,
    _PYPEDAL_OWNED_HANDLER,
    load_pedigree,
)

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
EXAMPLES = os.path.join(REPO, "PyPedal", "examples")
CORPUS = os.path.join(REPO, "tests", "fixtures", "pedigrees")

# The corpus pedigrees used by the remediation tests, with the pedformat each
# one actually requires. Getting these wrong produces an empty pedigree and a
# vacuously passing test, so they are stated once, here.
PEDFORMATS = {
    "mrode.ped": "asd",
    "new_lacy.ped": "asd",
    "generations.ped": "asdbx",
    "hartlandclark.ped": "asdb",
    "boichard2a.ped": "asdg",
    "doug.ped": "ASDx",
    "new_ids.ped": "ASD",
    "userfield.ped": "asdu",
    # Published worked examples transcribed from the primary sources. Each file
    # carries its own provenance header naming the figure, table and page.
    "boichard_fig1.ped": "asdg",
    "boichard_fig2.ped": "asdg",
    "ballou_fig1.ped": "asd",
    "suwanlee_fig1.ped": "asd",
}


def corpus(name):
    return os.path.join(CORPUS, name)


def load_corpus_from_path(path, pedformat, sepchar=" ", **overrides):
    """
    Load an arbitrary pedigree file, for purpose-built fixtures generated by a
    test. Output is confined the same way ``load_corpus`` confines it.
    """
    tmp = tempfile.mkdtemp(prefix="pypedal_test_")
    local = os.path.join(tmp, os.path.basename(path))
    shutil.copy(path, local)
    return _load(local, pedformat, sepchar, tmp, overrides)


def load_corpus(name, pedformat=None, sepchar=" ", **overrides):
    """Load a corpus pedigree with all generated output confined to a tmpdir."""
    tmp = tempfile.mkdtemp(prefix="pypedal_test_")
    local = os.path.join(tmp, name)
    shutil.copy(corpus(name), local)
    return _load(local, pedformat or PEDFORMATS[name], sepchar, tmp, overrides)


def _load(local, pedformat, sepchar, tmp, overrides):
    options = {
        "pedfile": local,
        "pedformat": pedformat,
        "sepchar": sepchar,
        "messages": "quiet",
        "renumber": True,
        "pedigree_is_renumbered": True,
        "pedigree_summary": 0,
    }
    options.update(overrides)
    cwd = os.getcwd()
    try:
        # Some routines write relative to the working directory rather than to
        # filetag; run the load from inside the tmpdir so those land there too.
        os.chdir(tmp)
        ped = load_pedigree(options)
    finally:
        os.chdir(cwd)
    # FileHandler is on the PyPedal logger; keep pytest output clean.
    logging.disable(logging.CRITICAL)
    return ped


def close_owned_pypedal_log_handlers():
    """Close PyPedal-owned logfile handlers so tests can delete temp logs.

    Only handlers marked with the production ``_pypedal_owned`` flag are
    removed. Host application handlers and the root logger are untouched.
    Does not call ``logging.shutdown()``.
    """
    package = logging.getLogger(PYPEDAL_LOGGER_NAME)
    for handler in list(package.handlers):
        if getattr(handler, _PYPEDAL_OWNED_HANDLER, False):
            package.removeHandler(handler)
            handler.close()


def write_temp_pedigree(rows, suffix=".ped"):
    """Write pedigree rows to a new temp file whose handle is already closed.

    ``tempfile.mkstemp`` leaves an open fd; Windows cannot delete that
    path until the fd is closed. Tests that later ``os.remove`` the file
    must not keep that descriptor.
    """
    fd, path = tempfile.mkstemp(suffix=suffix)
    os.close(fd)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(rows) + "\n")
    return path


@contextlib.contextmanager
def chdir_tmp():
    """
    Run a block with the working directory set to a fresh temporary directory.

    Several routines write output relative to the *working directory* rather
    than to ``filetag`` -- ``pyp_utils.fast_reorder(io='yes')`` writes
    ``_new_reordered__reordered.ped`` and ``_new_reordered__id_map.map``, and
    ``pyp_utils.renumber(io='yes')`` with no ``filetag`` writes
    ``_renumbered__renum.ped`` and ``_renumbered__id_map.map``. A test that
    asserts on those filenames therefore has to control the working directory,
    or it both depends on where pytest was invoked from and litters the
    repository. Yields the temporary directory.
    """
    tmp = tempfile.mkdtemp(prefix="pypedal_test_")
    cwd = os.getcwd()
    try:
        os.chdir(tmp)
        yield tmp
    finally:
        os.chdir(cwd)
        shutil.rmtree(tmp, ignore_errors=True)


def load_example(name, options):
    """
    Load a pedigree from ``PyPedal/examples`` with all generated output confined
    to a temporary directory.

    Unlike ``load_corpus``, this injects **no** options of its own: ``options``
    is used verbatim apart from ``pedfile``, which is repointed at a temporary
    copy of the named example. That keeps the behaviour of an existing test
    identical while stopping it from writing into the source tree -- ``filetag``
    is derived from the pedfile path (``pyp_newclasses.py:86``), so moving the
    input moves the output with it.
    """
    tmp = tempfile.mkdtemp(prefix="pypedal_test_")
    local = os.path.join(tmp, name)
    shutil.copy(os.path.join(EXAMPLES, name), local)
    opts = dict(options)
    opts["pedfile"] = local
    cwd = os.getcwd()
    try:
        os.chdir(tmp)
        ped = load_pedigree(opts)
    finally:
        os.chdir(cwd)
    logging.disable(logging.CRITICAL)
    return ped


def nrm_value(a, i, j):
    """Read A[i, j] from a matrix that may be dense NumPy or SciPy sparse."""
    v = a[i, j]
    try:
        return float(v)
    except (TypeError, ValueError):
        return float(v.toarray()[0, 0])


