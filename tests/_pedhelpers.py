def canonical_griffon_path():
    return os.path.join(EXAMPLES, CANONICAL_GRIFFON_PED)


def write_canonical_griffon_subset(dest_path, original_ids):
    """Copy matching records from the canonical Griffon file.

    Writes only under ``dest_path`` (caller-owned temporary location).
    Source lines are copied verbatim so sire, dam, sex, and date tokens
    match the canonical sample. Missing IDs are an error: the helper must
    not invent parents or silently drop animals.
    """
    wanted = {str(int(i)) for i in original_ids}
    found = set()
    dest_dir = os.path.dirname(os.path.abspath(dest_path))
    os.makedirs(dest_dir, exist_ok=True)
    with open(canonical_griffon_path(), encoding="utf-8") as src:
        with open(dest_path, "w", encoding="utf-8") as dst:
            for line in src:
                if not line.strip():
                    continue
                animal_id = line.split(",", 1)[0]
                if animal_id in wanted:
                    dst.write(line if line.endswith("\n") else line + "\n")
                    found.add(animal_id)
    missing = wanted - found
    extra = found - wanted
    if missing or extra:
        raise ValueError(
            "canonical Griffon subset mismatch: missing=%s extra=%s"
            % (sorted(missing, key=int)[:20], sorted(extra, key=int)[:20])
        )
    return dest_path


def _load_griffon_subset(original_ids, dest_name, options=None):
    tmp = tempfile.mkdtemp(prefix="pypedal_test_")
    local = os.path.join(tmp, dest_name)
    write_canonical_griffon_subset(local, original_ids)
    opts = dict(_GRIFFON_ASDXB)
    if options:
        opts.update({key: value for key, value in options.items() if key != "pedfile"})
    opts["pedfile"] = local
    cwd = os.getcwd()
    try:
        os.chdir(tmp)
        ped = load_pedigree(opts)
    finally:
        os.chdir(cwd)
    logging.disable(logging.CRITICAL)
    return ped


