def check_bounds(rows, reference, half_founder="phantom", limit=DEFAULT_EXACT_LIMIT):
    """
    Verify the two DERIVED bounds on every enumerated outcome, not on the mean.

        N_g >= 1/2                           (SUM f_k = 1, so SUM f_k^2 <= 1)
        N_g <= f_e computed from the SAME realised frequencies

    Returns ``(ok, worst_ng, min_slack)`` where ``min_slack`` is the smallest
    ``f_e - N_g`` seen; a zero slack is legal and means some outcome had every
    founder's two genes equally frequent.
    """
    check_topological(rows)
    plan = _choice_plan(rows, half_founder)
    b = n_binary_choices(rows, half_founder)
    if (1 << b) > limit:
        raise ExactEnumerationTooLarge("state space 2**%d exceeds limit %d" % (b, limit))
    worst = None
    slack = None
    for mask in range(1 << b):
        geno = _segregate(rows, plan, [(mask >> i) & 1 for i in range(b)])
        v = ng(geno, reference)
        fe = f_e_realised(geno, reference)
        if v < Fraction(1, 2):
            return False, float(v), None
        if v > fe:
            return False, float(v), float(fe - v)
        worst = v if worst is None or v < worst else worst
        d = fe - v
        slack = d if slack is None or d < slack else slack
    return True, float(worst), float(slack)


