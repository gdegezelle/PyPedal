def gene_counts(geno, reference):
    """Gene counting in the population under study (eq. 2's ``f_k``, unnormalised)."""
    counts = {}
    for a in reference:
        for g in geno[a]:
            counts[g] = counts.get(g, 0) + 1
    return counts


def sum_f2(geno, reference):
    """SUM_{k=1..2f} f_k^2, exactly, as a Fraction."""
    counts = gene_counts(geno, reference)
    n = sum(counts.values())
    if n == 0:
        raise ValueError("the population under study contains no gene copies; "
                         "SUM f_k^2 is undefined")
    return Fraction(sum(c * c for c in counts.values()), n * n)


def ng(geno, reference):
    """Per-replicate N_g = 1/(2 SUM f_k^2), exactly, as a Fraction."""
    return 1 / (2 * sum_f2(geno, reference))


def gene_diversity(geno, reference):
    """
    1 - SUM f_k^2, the gene diversity of R. Lacy's Table 1 column H is the mean
    of this over his 10 000 simulations, and reproducing it calibrates the
    segregation and counting mechanics of this module -- and nothing else.
    """
    return 1 - sum_f2(geno, reference)


def f_e_realised(geno, reference):
    """
    f_e computed from the SAME realised frequencies as ``ng``, i.e.
    1/SUM_i p_i^2 with p_i = f_i1 + f_i2 pooled over founder i's two genes.

    This is the only f_e against which ``N_g <= f_e`` is a derived inequality
    rather than an observation. It is NOT PyPedal's f_e, which uses expected
    contributions from the numerator relationship matrix.
    """
    counts = gene_counts(geno, reference)
    n = sum(counts.values())
    per_founder = {}
    for g, c in counts.items():
        origin = g.split(".")[0]
        per_founder[origin] = per_founder.get(origin, 0) + c
    total = sum(Fraction(c, n) ** 2 for c in per_founder.values())
    return 1 / total


