#!/usr/bin/env python3
"""
INDEPENDENT oracle for BOICHARD's N_g -- the effective number of
founder genomes remaining in the population under study.

Does not import PyPedal. Does not import, wrap or consult
``oracle_lacy.f_g_lacy``.

    Boichard D, Maignel L, Verrier E (1997) "The value of using probabilities
    of gene origin to measure genetic variability in a population."
    Genet Sel Evol 29:5-23.  Article p.10-11 (PDF p.7-8), equation [2]:

        N_a = 1 / SUM_{k=1..2f} f_k^2
        N_g = N_a / 2 = 1 / (2 * SUM_{k=1..2f} f_k^2)

    "At a given locus, each founder is characterized by its two genes and 2f
    founder genes are generated. Then the segregation is simulated throughout
    the complete pedigree and the genotype of each progeny is generated by
    randomly sampling one allele from each parent. Gene frequencies f_k are
    determined by gene counting in the population under study."

THIS IS NOT LACY'S f_g -- AND THAT IS THE POINT OF THE MODULE
--------------------------------------------------------------
Boichard p.11 calls N_g the quantity "called 'founder genome equivalent' by
Lacy, 1989". That is a NAMING claim in passing; the paper derives no equivalence
and the two are different functionals:

    Lacy (1989) p.115      f_g = 1 / SUM (p_i^2 / r_i)
                           r_i = expected proportion of founder i's alleles
                                 RETAINED (a survival probability)

    Boichard (1997) eq.2   N_g = 1 / (2 * SUM f_k^2)
                           f_k = FREQUENCY of founder gene k in R

Lacy p.117-118 confirms his own estimator is the retention one: "Analysis of
founder allele *retention* in 10,000 gene drop computer simulations yielded
23.79 founder genome equivalents". ``test_founder_genomes_oracle.py`` pins the
resulting numerical disagreement on Lacy's own published Table 1 and on
``new_lacy.ped``, so that no later reader can quietly substitute one for the
other. Use ``oracle_lacy.f_g_lacy`` for f_g. Use this module for N_g. Never one
as the oracle for the other.

CALIBRATION, AND THE LIMIT OF WHAT IT PROVES
--------------------------------------------
``gene_diversity()`` reproduces Lacy's Table 1 column H, which he obtained from
10 000 gene-drop simulations. That agreement validates the SEGREGATION AND
GENE-COUNTING MECHANICS of this module -- nothing more. It emphatically does
NOT show that Lacy f_g equals Boichard N_g; on the very same pedigrees the two
disagree by 8-11%.

BOUNDS
------
``N_g >= 0.5``, not ``>= 1``. With f_k >= 0 and SUM f_k = 1 we have
0 < SUM f_k^2 <= 1, so N_g = 1/(2 SUM f_k^2) >= 1/2, with equality exactly when
one founder gene is FIXED in R. A fixed founder gene is a legitimate outcome of
gene dropping, so ``N_g < 1`` is a valid result and must never be rejected.

``N_g <= f_e`` holds PER REPLICATE against the f_e computed from the SAME
realised frequencies, by (a+b)^2 <= 2(a^2+b^2) applied to p_i = f_i1 + f_i2:

    SUM_i p_i^2 <= 2 SUM_k f_k^2   =>   N_g = 1/(2 SUM f_k^2) <= 1/SUM p_i^2 = f_e

with equality exactly when every founder's two genes are equally frequent in R.
``f_e_realised()`` computes that same-replicate f_e so the gate is exact rather
than an appeal to Boichard's Table II. The relation between E[N_g] and the
NRM-based *expected* f_e does NOT follow from this derivation and is reported as
an observation, never enforced.
"""
