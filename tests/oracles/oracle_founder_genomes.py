#: Half-founder representations. Both are *research* representations; neither is
#: a production decision. See FG-10 in the Finding-31 document.
HALF_FOUNDER_MODES = ("phantom", "slot")

#: Exhaustive enumeration is 2**(number of binary segregation choices). The cap
#: is a refusal threshold, not a silent fallback: past it the caller must ask
#: for Monte Carlo explicitly, so that an "exact" label is never attached to a
#: sampled result.
DEFAULT_EXACT_LIMIT = 1 << 20


class ExactEnumerationTooLarge(Exception):
    """Raised instead of silently sampling when the state space exceeds the cap."""


