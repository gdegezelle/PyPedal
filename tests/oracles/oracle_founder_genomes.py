def distribution_bruteforce(rows, reference, half_founder="phantom",
                            limit=DEFAULT_EXACT_LIMIT):
    """
    The EXACT distribution of SUM f_k^2 by enumerating every segregation
    outcome, as ``{Fraction(sum_f2): Fraction(probability)}``.

    Every outcome is equally likely, so probabilities are multiples of
    ``1/2**b``; they are Fractions so that two distributions can be compared for
    exact equality rather than for closeness, which is what FG-10 needs.

    This is the DEFINITION, and it is O(2**b). ``distribution()`` computes the
    same thing far faster by factorising; the two are cross-checked against each
    other in ``tests/test_founder_genomes_oracle.py`` so that the fast path can
    never quietly diverge from the definition it claims to implement.
    """
    check_topological(rows)
    plan = _choice_plan(rows, half_founder)
    b = n_binary_choices(rows, half_founder)
    if (1 << b) > limit:
        raise ExactEnumerationTooLarge(
            "%d binary segregation choices means 2**%d = %d outcomes, above the "
            "limit of %d. Raise limit= deliberately, or use mc_ng() and label "
            "the result as sampled." % (b, b, 1 << b, limit))
    dist = {}
    for mask in range(1 << b):
        bits = [(mask >> i) & 1 for i in range(b)]
        s = sum_f2(_segregate(rows, plan, bits), reference)
        dist[s] = dist.get(s, 0) + 1
    total = Fraction(1, 1 << b)
    return {s: c * total for s, c in dist.items()}


def _binomial_row(m):
    """``[(k, C(m,k)/2**m) for k in 0..m]`` as exact Fractions."""
    row, c = [], 1
    for k in range(m + 1):
        row.append((k, Fraction(c, 1 << m)))
        c = c * (m - k) // (k + 1)
    return row


def distribution(rows, reference, half_founder="phantom", limit=DEFAULT_EXACT_LIMIT):
    """
    The EXACT distribution of SUM f_k^2, factorised.

    Identical output to ``distribution_bruteforce`` -- same Fractions, same
    keys -- but it does not enumerate 2**b outcomes.

    THE FACTORISATION. Members of R that are nobody's parent are conditionally
    independent given their parents' genotypes, and members sharing a parent
    pair are exchangeable: only HOW MANY of them drew each parental gene matters
    to a gene count, not which. So a group of ``m`` such full sibs contributes
    ``Binomial(m, 1/2)`` copies of each parent's first gene rather than 2**(2m)
    enumerated outcomes. Animals that are parents, and animals with an unknown
    parental slot (whose phantom genes are unique per animal and therefore not
    exchangeable), are still enumerated exhaustively.

    Boichard's Family 1 drops from 2**20 outcomes to 16 x 81; Lacy's Table 1
    row (4,8) from 2**24 to 25 x 81.
    """
    check_topological(rows)
    if half_founder not in HALF_FOUNDER_MODES:
        raise ValueError("half_founder must be one of {!r}".format(HALF_FOUNDER_MODES))
    reference = list(reference)
    if not reference:
        raise ValueError("the population under study is empty; "
                         "SUM f_k^2 is undefined")

    parents_of_someone = set()
    for _a, s, d in rows:
        for p in (s, d):
            if p != MISSING:
                parents_of_someone.add(p)
    founders = set(true_founders(rows))
    ref = set(reference)

    #: exchangeable only if both parents are known -- a phantom gene is unique
    #: to its own animal, so half-founders are never interchangeable.
    def groupable(a, s, d):
        return (a in ref and a not in parents_of_someone and a not in founders
                and s != MISSING and d != MISSING)

    groups = {}
    enumerate_rows = []
    for a, s, d in rows:
        if a in founders:
            continue
        if groupable(a, s, d):
            groups.setdefault((s, d), []).append(a)
        elif a in parents_of_someone or a in ref:
            enumerate_rows.append((a, s, d))
        # else: not in R and nobody's parent -- affects no gene count at all

    plan = _choice_plan(enumerate_rows, half_founder)
    b = sum(1 for _a, s0, s1 in plan for src in (s0, s1) if src[0] != "fixed")
    if (1 << b) > limit:
        raise ExactEnumerationTooLarge(
            "even after factorising, %d animals must be enumerated exhaustively "
            "(2**%d = %d outcomes), above the limit of %d. Raise limit= "
            "deliberately, or use mc_ng() and label the result as sampled."
            % (len(plan), b, 1 << b, limit))

    n = 2 * len(reference)
    dist = {}
    for mask in range(1 << b):
        bits = [(mask >> i) & 1 for i in range(b)]
        seed = {}
        for f in founders:
            seed[f] = ("F%d.1" % f, "F%d.2" % f)
        geno = _segregate(enumerate_rows, plan, bits, geno=seed)

        base = {}
        for a in reference:
            if a in geno:
                for g in geno[a]:
                    base[g] = base.get(g, 0) + 1
        # {counts-tuple: probability}, convolved group by group
        genes = sorted(set(list(base)
                           + [g for (s, d) in groups for p in (s, d) for g in geno[p]]))
        idx = {g: i for i, g in enumerate(genes)}
        vec = [0] * len(genes)
        for g, c in base.items():
            vec[idx[g]] = c
        states = {tuple(vec): Fraction(1)}
        for (s, d), members in groups.items():
            m = len(members)
            nxt = {}
            for k, pk in _binomial_row(m):
                for j, pj in _binomial_row(m):
                    delta = [0] * len(genes)
                    delta[idx[geno[s][0]]] += k
                    delta[idx[geno[s][1]]] += m - k
                    delta[idx[geno[d][0]]] += j
                    delta[idx[geno[d][1]]] += m - j
                    w = pk * pj
                    for state, p in states.items():
                        key = tuple(state[i] + delta[i] for i in range(len(genes)))
                        nxt[key] = nxt.get(key, Fraction(0)) + p * w
            states = nxt
        weight = Fraction(1, 1 << b)
        for state, p in states.items():
            total = sum(state)
            if total != n:
                raise AssertionError(
                    "gene counting lost copies: %d counted, %d expected" % (total, n))
            s2 = Fraction(sum(c * c for c in state), n * n)
            dist[s2] = dist.get(s2, Fraction(0)) + p * weight
    return dist


def exact_ng(rows, reference, half_founder="phantom", limit=DEFAULT_EXACT_LIMIT):
    """
    Exhaustive enumeration. Returns a dict with

        n_g          E[1/(2 SUM f_k^2)]  -- the source estimator, see below
        inv_mean_s   1/(2 E[SUM f_k^2])  -- the OTHER candidate estimator
        e_sum_f2     E[SUM f_k^2]
        h            E[1 - SUM f_k^2], Lacy's H
        min_ng/max_ng
        outcomes     size of the enumerated state space

    WHICH ESTIMATOR IS BOICHARD'S is not a matter of taste: Table II Family 2
    publishes N_g = 1.1, and on that pedigree E[1/(2S)] = 1.1063... while
    1/(2 E[S]) = 1 exactly. Boichard averages the PER-REPLICATE N_g. ``n_g`` is
    therefore the source-consistent estimator and ``inv_mean_s`` is retained
    only so that the discriminator can be shown rather than asserted.
    """
    dist = distribution(rows, reference, half_founder, limit)
    e_s = sum(p * s for s, p in dist.items())
    e_ng = sum(p / (2 * s) for s, p in dist.items())
    return {
        "n_g": float(e_ng),
        "n_g_exact": e_ng,
        "inv_mean_s": float(1 / (2 * e_s)),
        "e_sum_f2": float(e_s),
        "h": float(1 - e_s),
        "min_ng": float(min(1 / (2 * s) for s in dist)),
        "max_ng": float(max(1 / (2 * s) for s in dist)),
        "outcomes": sum(1 for _ in dist),
        # the size of the definitional state space, NOT the amount of work done:
        # distribution() factorises exchangeable full sibs away. The two agree
        # exactly -- see the brute-force cross-check in the oracle test.
        "state_space": 1 << n_binary_choices(rows, half_founder),
        "method": "exact (factorised enumeration)",
    }


# ---------------------------------------------------------------------------
# Monte Carlo
# ---------------------------------------------------------------------------

def mc_ng(rows, reference, replicates, seed, half_founder="phantom"):
    """
    Monte-Carlo estimate, for pedigrees whose state space exceeds the exact cap.

    Uses a LOCAL ``random.Random(seed)``: this module never touches the process
    -global random state, which is one of the defects it exists to characterise.
    Returns the mean and the sample variance of the per-replicate N_g, so that
    a caller can state a tolerance from the measured variance instead of from a
    hopeful constant.
    """
    check_topological(rows)
    plan = _choice_plan(rows, half_founder)
    b = n_binary_choices(rows, half_founder)
    rng = random.Random(seed)
    total = 0.0
    total_sq = 0.0
    for _ in range(replicates):
        bits = [rng.getrandbits(1) for _ in range(b)]
        v = float(ng(_segregate(rows, plan, bits), reference))
        total += v
        total_sq += v * v
    mean = total / replicates
    var = max(0.0, total_sq / replicates - mean * mean)
    return {
        "n_g": mean,
        "variance": var,
        "sem": (var / replicates) ** 0.5,
        "replicates": replicates,
        "seed": seed,
    }


