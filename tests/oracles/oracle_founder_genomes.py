def true_founders(rows):
    """
    Animals with BOTH parents unknown.

    Deliberately different from ``oracle_boichard.founders``, which implements
    Boichard p.7's founder definition for the f_e/f_a bounds and therefore
    counts half-founders as founders. Gene dropping needs the animals that
    actually originate two founder genes, which a half-founder does not: it
    originates one, through its unknown parental side.
    """
    return [a for a, s, d in rows if s == MISSING and d == MISSING]


def founder_genes(rows, half_founder="phantom"):
    """
    The ``2f`` founder genes of eq. 2, as ordered labels.

    ``phantom``  each unknown parental slot is its own founder with two unique
                 genes (Lacy p.113; Boichard App. A step 4; Baumung 2015 p.102).
    ``slot``     each unknown parental slot contributes exactly ONE unique gene,
                 placed directly in the slot.

    FG-10 asks whether the two give the same distribution of SUM f_k^2. They
    generate DIFFERENT numbers of labels, which is precisely why the question is
    about the distribution of the statistic and not about the label count.
    """
    if half_founder not in HALF_FOUNDER_MODES:
        raise ValueError("half_founder must be one of {!r}".format(HALF_FOUNDER_MODES))
    genes = []
    for a in true_founders(rows):
        genes.extend(["F%d.1" % a, "F%d.2" % a])
    for a, side in unknown_parent_slots(rows):
        if half_founder == "phantom":
            genes.extend(["P%d%s.1" % (a, side[0]), "P%d%s.2" % (a, side[0])])
        else:
            genes.append("P%d%s" % (a, side[0]))
    return genes


def _choice_plan(rows, half_founder):
    """
    One entry per animal that is not a true founder, as
    ``(animal, sire_source, dam_source)`` where each source is either

        ('parent', parent_id)        sample one of that parent's two genes
        ('phantom', (g1, g2))        sample one of the phantom founder's genes
        ('fixed', g)                 no choice at all -- the slot's single gene

    The number of binary choices is the number of non-``fixed`` sources, and
    that is what sizes the exhaustive enumeration.
    """
    plan = []
    for a, s, d in rows:
        if s == MISSING and d == MISSING:
            continue
        sources = []
        for parent, side in ((s, "sire"), (d, "dam")):
            if parent != MISSING:
                sources.append(("parent", parent))
            elif half_founder == "phantom":
                sources.append(("phantom", ("P%d%s.1" % (a, side[0]),
                                            "P%d%s.2" % (a, side[0]))))
            else:
                sources.append(("fixed", "P%d%s" % (a, side[0])))
        plan.append((a, sources[0], sources[1]))
    return plan


def n_binary_choices(rows, half_founder="phantom"):
    return sum(1
               for _a, s0, s1 in _choice_plan(rows, half_founder)
               for src in (s0, s1)
               if src[0] != "fixed")


def _segregate(rows, plan, bits, geno=None):
    """
    Realise one gene drop. ``bits`` is an iterable of 0/1 consumed in plan
    order; ``rows`` must be topologically ordered so a parent's genotype exists
    before it is sampled.

    ``geno`` seeds the founder genotypes. It defaults to the true founders of
    ``rows``; ``distribution()`` passes its own, because the rows it enumerates
    deliberately exclude founders and animals it has factorised out.
    """
    geno = dict(geno) if geno is not None else {}
    for a in true_founders(rows):
        geno[a] = ("F%d.1" % a, "F%d.2" % a)
    it = iter(bits)
    for a, src0, src1 in plan:
        got = []
        for kind, payload in (src0, src1):
            if kind == "fixed":
                got.append(payload)
            elif kind == "phantom":
                got.append(payload[next(it)])
            else:
                got.append(geno[payload][next(it)])
        geno[a] = (got[0], got[1])
    return geno


